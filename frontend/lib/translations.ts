export type TKey = keyof typeof t.en;

export function tr(
  lang: Lang,
  key: TKey,
  vars?: Record<string, string | number>,
): string {
  const dict = t[lang] as Record<string, string>;
  const val = dict[key] ?? (t.en as Record<string, string>)[key] ?? key;
  if (!vars) return val;
  return val.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}
